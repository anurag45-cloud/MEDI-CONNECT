// Helper to generate beds for each hospital
export function generateDemoBeds(): Bed[] {
  const beds: Bed[] = [];
  
  DEMO_HOSPITALS.forEach((hosp) => {
    // Generate General beds (15-20)
    for (let i = 1; i <= 15; i++) {
      const isAvailable = i % 3 !== 0;
      beds.push({
        id: `${hosp.id}-gen-${i.toString().padStart(2, "0")}`,
        hospital_id: hosp.id,
        hospital_name: hosp.name,
        ward: "general",
        bed_number: `GEN-${i.toString().padStart(2, "0")}`,
        price_per_day: 1500,
        status: isAvailable ? "available" : i % 5 === 0 ? "occupied" : "booked",
        created_at: "2024-01-01T00:00:00Z",
        updated_at: "2026-10-24T00:00:00Z"
      });
    }

    // Generate Emergency beds (5-8)
    for (let i = 1; i <= 6; i++) {
      const isAvailable = i <= (hosp.available_emergency_beds || 2);
      beds.push({
        id: `${hosp.id}-emg-${i.toString().padStart(2, "0")}`,
        hospital_id: hosp.id,
        hospital_name: hosp.name,
        ward: "emergency",
        bed_number: `EMG-${i.toString().padStart(2, "0")}`,
        price_per_day: 3500,
        status: isAvailable ? "available" : "occupied",
        created_at: "2024-01-01T00:00:00Z",
        updated_at: "2026-10-24T00:00:00Z"
      });
    }

    // Generate ICU beds (4-6)
    for (let i = 1; i <= 5; i++) {
      beds.push({
        id: `${hosp.id}-icu-${i.toString().padStart(2, "0")}`,
        hospital_id: hosp.id,
        hospital_name: hosp.name,
        ward: "icu",
        bed_number: `ICU-${i.toString().padStart(2, "0")}`,
        price_per_day: 6000,
        status: i === 1 ? "available" : "occupied",
        created_at: "2024-01-01T00:00:00Z",
        updated_at: "2026-10-24T00:00:00Z"
      });
    }
  });

  return beds;
}

export const DEMO_BEDS: Bed[] = generateDemoBeds();
